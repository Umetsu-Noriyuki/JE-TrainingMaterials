-- ============================================================================
-- 1. テーブル定義（第1章〜第6章のすべての検証クエリに対応）
-- ============================================================================

-- ① 顧客マスタ（第5章: 暗黙の型変換 customer_code VARCHAR2 の検証用）
CREATE TABLE customers (
    customer_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_code  VARCHAR2(20) NOT NULL,  -- 意図的に文字列型で定義
    customer_name  VARCHAR2(100) NOT NULL,
    email          VARCHAR2(255) NOT NULL, -- 第3章: 関数インデックス UPPER(email) 検証用
    gender         CHAR(1) NOT NULL,       -- 第6章: 低カーディナリティ（M/F）検証用
    created_at     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- ② ユーザーテーブル（第5章: SUBSTR / LIKE 前方一致・中間一致の検証用）
CREATE TABLE users (
    user_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_code      VARCHAR2(20) NOT NULL,  -- 'JPN-000001' 形式
    user_name      VARCHAR2(100) NOT NULL,
    department     VARCHAR2(50),           -- NULLを含むカラム（IS NULL 検証用）
    created_at     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- ③ 注文トランザクション（第2章〜第6章: 複合・カバリング・部分・FKロック検証用）
CREATE TABLE orders (
    order_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id    NUMBER NOT NULL,        -- 第6章: 外部キー（最初はFKインデックスなし）
    status         VARCHAR2(20) NOT NULL,  -- 'COMPLETED'(99%) と 'PENDING'(1%) の偏りデータ
    price          NUMBER(10) NOT NULL,    -- 第5章: 列に対する演算（price * 1.1）検証用
    item_name      VARCHAR2(100) NOT NULL, -- 第5章: 中間一致 LIKE '%ノートPC%' 検証用
    ordered_at     TIMESTAMP NOT NULL,     -- 第4章: 複合インデックス (status, ordered_at) 検証用
    CONSTRAINT fk_orders_customer FOREIGN KEY (customer_id) REFERENCES customers(customer_id)
);

-- ============================================================================
-- 2. テストデータ一括投入（計 約65万件：階層 CONNECT BY LEVEL による高速生成）
-- ============================================================================

-- customers: 50,000件投入
INSERT /*+ APPEND */ INTO customers (customer_code, customer_name, email, gender, created_at)
SELECT
    LPAD(TO_CHAR(LEVEL), 6, '0'),
    '顧客_' || LEVEL,
    'User' || LEVEL || '@Example.com',
    CASE WHEN MOD(LEVEL, 2) = 0 THEN 'M' ELSE 'F' END,
    TIMESTAMP '2025-01-01 00:00:00' + NUMTODSINTERVAL(LEVEL, 'MINUTE')
FROM dual
CONNECT BY LEVEL <= 50000;
COMMIT;

-- users: 100,000件投入（先頭3文字に国コード 'JPN' / 'USA' / 'GBR' を付与）
INSERT /*+ APPEND */ INTO users (user_code, user_name, department, created_at)
SELECT
    CASE MOD(LEVEL, 3)
        WHEN 0 THEN 'JPN-' || LPAD(TO_CHAR(LEVEL), 6, '0')
        WHEN 1 THEN 'USA-' || LPAD(TO_CHAR(LEVEL), 6, '0')
        ELSE        'GBR-' || LPAD(TO_CHAR(LEVEL), 6, '0')
    END,
    'ユーザー_' || LEVEL,
    CASE WHEN MOD(LEVEL, 10) = 0 THEN NULL ELSE '開発' || (MOD(LEVEL, 5) + 1) || '課' END,
    TIMESTAMP '2025-01-01 00:00:00' + NUMTODSINTERVAL(LEVEL, 'SECOND')
FROM dual
CONNECT BY LEVEL <= 100000;
COMMIT;

-- orders: 500,000件投入
-- ※第3章（部分インデックス相当）検証のため、99%を 'COMPLETED'、1%（5,000件）のみ 'PENDING' に設定
INSERT /*+ APPEND */ INTO orders (customer_id, status, price, item_name, ordered_at)
SELECT
    MOD(LEVEL, 50000) + 1,
    CASE WHEN MOD(LEVEL, 100) = 0 THEN 'PENDING' ELSE 'COMPLETED' END,
    (MOD(LEVEL, 50) + 1) * 1000,
    CASE MOD(LEVEL, 4)
        WHEN 0 THEN 'ビジネスノートPC Pro 14'
        WHEN 1 THEN 'ワイヤレスマウス静音モデル'
        WHEN 2 THEN '4K対応27インチモニター'
        ELSE        'USB-Cドッキングステーション'
    END,
    TIMESTAMP '2025-01-01 00:00:00' + NUMTODSINTERVAL(LEVEL, 'SECOND')
FROM dual
CONNECT BY LEVEL <= 500000;
COMMIT;

-- ============================================================================
-- 3. 初期インデックス作成（各章の検証ベースライン用）
-- ============================================================================

-- 第3章（関数インデックス）・第5章（暗黙の型変換）検証用
CREATE UNIQUE INDEX idx_customers_code ON customers(customer_code);
CREATE INDEX idx_customers_upper_email ON customers(UPPER(email));

-- 第5章（SUBSTR / 前方一致LIKE）検証用
CREATE INDEX idx_users_code ON users(user_code);

-- 第4章（複合インデックス・左端一致）・第5章（演算・LIKE）検証用
CREATE INDEX idx_orders_status_ordered_at ON orders(status, ordered_at);
CREATE INDEX idx_orders_price ON orders(price);
CREATE INDEX idx_orders_item_name ON orders(item_name);

-- 第3章（部分インデックスのOracle表現）検証用
-- OracleのBツリーは「すべてNULLのキー」を格納しない仕様を利用し、PENDINGの1%だけをインデックス化
CREATE INDEX idx_orders_pending_only ON orders(
    CASE WHEN status = 'PENDING' THEN ordered_at ELSE NULL END
);

